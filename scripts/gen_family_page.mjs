// Generates cloud/aws/ring-private/family-page.mjs from family-page/index.html + app.js, so the Lambda serves the family page
// without reading files at run time (the pinned artifact allows only a fixed import set). Run after editing either file;
// cloud/aws/ring-private/tests/family-relay.test.mjs fails if the generated module is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'cloud', 'aws', 'ring-private');
export function renderFamilyPageModule() {
  const html = readFileSync(join(dir, 'family-page', 'index.html'), 'utf8');
  const js = readFileSync(join(dir, 'family-page', 'app.js'), 'utf8');
  return '// GENERATED by scripts/gen_family_page.mjs from family-page/index.html and family-page/app.js. Do not edit.\n'
    + `export const FAMILY_PAGE_HTML = ${JSON.stringify(html)};\n`
    + `export const FAMILY_PAGE_JS = ${JSON.stringify(js)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(dir, 'family-page.mjs'), renderFamilyPageModule(), { mode: 0o644 });
  console.log('wrote cloud/aws/ring-private/family-page.mjs');
}
